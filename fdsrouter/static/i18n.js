const LANG_STORAGE_KEY = "fdsrouter.lang";
const THEME_STORAGE_KEY = "fdsrouter.theme";

function getLang() {
  try {
    const stored = localStorage.getItem(LANG_STORAGE_KEY);
    if (stored && STRINGS[stored]) return stored;
  } catch (e) {
    // localStorage unavailable -- fall through to default
  }
  // English by default: the tool is used beyond German-speaking offices, and every operator
  // who prefers German switches once in the settings, which is then remembered.
  return "en";
}

function setLang(lang) {
  if (!STRINGS[lang]) return;
  try {
    localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch (e) {
    // best effort only
  }
}

function getTheme() {
  try {
    const stored = localStorage.getItem(THEME_STORAGE_KEY);
    if (stored === "light" || stored === "dark") return stored;
  } catch (e) {
    // localStorage unavailable -- fall through to default
  }
  return "dark";
}

function setTheme(theme) {
  try {
    localStorage.setItem(THEME_STORAGE_KEY, theme);
  } catch (e) {
    // best effort only
  }
  document.documentElement.setAttribute("data-theme", theme);
}

function t(key, vars) {
  const lang = getLang();
  let template = (STRINGS[lang] && STRINGS[lang][key]) || STRINGS.en[key] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      template = template.replaceAll(`{${k}}`, v);
    }
  }
  return template;
}

function applyStaticTranslations() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
}
